    private void buttonInsertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonInsertarActionPerformed
        try {
            Date fechaSeleccionada = (Date) spinnerFechaConsulta.getValue();
            Timestamp timestampSql = new Timestamp(fechaSeleccionada.getTime());

            Object[] res = cnx.ejecutarCRUD(
                    "gestionar_consulta",
                    new Object[]{
                            "INSERT",
                            textFieldFolio.getText(),
                            timestampSql,
                            Float.parseFloat(textFieldPeso.getText()),
                            Integer.parseInt(textFieldEstatura.getText()),
                            textFieldPresion.getText(),
                            textAreaSintomas.getText(),
                            textAreaDiagnostico.getText(),
                            comboBoxEstado.getSelectedItem().toString(),
                            comboBoxPaciente.getSelectedItem().toString(),
                            comboBoxMedico.getSelectedItem().toString(),
                    }
            );
            JOptionPane.showMessageDialog(this,"Estado:" + res[0] + "\n Mensaje: " + res[1]);
            if(Integer.parseInt(res[0].toString())==1){
                cnx.entablar(todo, tableConsultas);
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this,"Error al insertar registro");
        }
    }//GEN-LAST:event_buttonInsertarActionPerformed

